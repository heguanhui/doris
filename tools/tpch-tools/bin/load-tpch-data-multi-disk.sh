##############################################################
# This script is used to load generated TPC-H data set into Doris.
# for table lineitem, orders, partsupp, they will be loading in parallel.
#
# Supports multi-disk data directories via manifest file.
# If meta/data-manifest.json exists (written by gen-tpch-data-multi-disk.sh),
# the script reads data_dirs and file lists from it, validates shard
# completeness, then loads.
# If no manifest exists, falls back to single-directory (tpch-data/)
# behavior, identical to load-tpch-data.sh.
##############################################################

set -eo pipefail

ROOT=$(dirname "$0")
ROOT=$(
    cd "${ROOT}"
    pwd
)

CURDIR="${ROOT}"
TPCH_DATA_DIR="${CURDIR}/tpch-data"

MANIFEST_NAME="data-manifest.json"
META_DIR="${CURDIR}/meta"

usage() {
    echo "
Usage: $0 <options>
  Optional options:
    -c             parallelism to load data of lineitem, orders, partsupp, default is 5.
    -x             use transaction id. multi times of loading with the same id won't load duplicate data.

  Multi-disk:
    If meta/data-manifest.json exists (generated by gen-tpch-data-multi-disk.sh),
    data directories and file lists are read from the manifest automatically.
    If no manifest, falls back to single directory (tpch-data/) behavior.

  Eg.
    $0              load data using default value.
    $0 -c 10        load lineitem, orders, partsupp table data using parallelism 10.
    $0 -x blabla    use transaction id \"blabla\".
  "
    exit 1
}

OPTS=$(getopt \
    -n "$0" \
    -o '' \
    -o 'hc:x:' \
    -- "$@")

eval set -- "${OPTS}"

PARALLEL=5
HELP=0
TXN_ID=""

if [[ $# == 0 ]]; then
    usage
fi

while true; do
    case "$1" in
    -h)
        HELP=1
        shift
        ;;
    -c)
        PARALLEL=$2
        shift 2
        ;;
    -x)
        TXN_ID=$2
        shift 2
        ;;
    --)
        shift
        break
        ;;
    *)
        echo "Internal error"
        exit 1
        ;;
    esac
done

if [[ "${HELP}" -eq 1 ]]; then
    usage
fi

echo "Parallelism: ${PARALLEL}"

# Determine mode: manifest-based or single-directory fallback
MANIFEST_PATH=""
SEARCH_DIRS=()
MANIFEST_MODE=0

# Check for manifest in meta/ directory
if [[ -f "${META_DIR}/${MANIFEST_NAME}" ]]; then
    MANIFEST_PATH="${META_DIR}/${MANIFEST_NAME}"
elif [[ -d "${TPCH_DATA_DIR}" ]]; then
    # No manifest — old-style single directory
    echo "Mode: single-disk (no manifest, using ${TPCH_DATA_DIR})"
    SEARCH_DIRS=("${TPCH_DATA_DIR}")
else
    echo "Error: ${TPCH_DATA_DIR} does not exist and no ${MANIFEST_NAME} found in ${META_DIR}."
    echo "Run gen-tpch-data-multi-disk.sh first to generate data."
    exit 1
fi

# If manifest found, parse it
if [[ -n "${MANIFEST_PATH}" ]]; then
    echo "Found manifest: ${MANIFEST_PATH}"

    # Validate manifest is not empty
    if [[ ! -s "${MANIFEST_PATH}" ]]; then
        echo "Error: Manifest file ${MANIFEST_PATH} is empty."
        exit 1
    fi

    # Parse data_dirs from manifest using python (more reliable than pure bash for JSON)
    if command -v python3 &>/dev/null; then
        PYTHON_CMD=python3
    elif command -v python &>/dev/null; then
        PYTHON_CMD=python
    else
        echo "Error: python3 or python is required to parse manifest JSON."
        exit 1
    fi

    # Validate manifest structure
    VALIDATION=$("${PYTHON_CMD}" -c "
import json, sys
with open('${MANIFEST_PATH}') as f:
    m = json.load(f)
required = ['total_table_num', 'data_dirs', 'scale_factor', 'data_file_distribution']
for key in required:
    if key not in m:
        print(f'Missing key: {key}')
        sys.exit(1)
if not isinstance(m['data_dirs'], list) or len(m['data_dirs']) == 0:
    print('data_dirs must be a non-empty list')
    sys.exit(1)
if not isinstance(m['data_file_distribution'], dict):
    print('data_file_distribution must be a dict')
    sys.exit(1)
if m['total_table_num'] != len(m['data_file_distribution']):
    print(f'total_table_num ({m[\"total_table_num\"]}) != actual table count ({len(m[\"data_file_distribution\"])})')
    sys.exit(1)
for table, info in m['data_file_distribution'].items():
    if 'shard' not in info or 'data_files' not in info:
        print(f'Table {table} missing shard or data_files')
        sys.exit(1)
    if info['shard'] != len(info['data_files']):
        print(f'Table {table}: shard ({info[\"shard\"]}) != file count ({len(info[\"data_files\"])})')
        sys.exit(1)
print('OK')
" 2>&1)
    if [[ "${VALIDATION}" != "OK" ]]; then
        echo "Error: Manifest validation failed: ${VALIDATION}"
        exit 1
    fi
    echo "Manifest validation passed."

    # Extract data_dirs from manifest
    while IFS= read -r -d '' dir; do
        SEARCH_DIRS+=("${dir}")
    done < <("${PYTHON_CMD}" -c "
import json
with open('${MANIFEST_PATH}') as f:
    m = json.load(f)
for d in m['data_dirs']:
    print(d, end='\0')
" 2>/dev/null)

    NUM_DIRS=${#SEARCH_DIRS[@]}
    echo "Mode: manifest (${NUM_DIRS} data directories)"

    # Validate all data directories exist
    for dir in "${SEARCH_DIRS[@]}"; do
        if [[ ! -d "${dir}" ]]; then
            echo "Error: Data directory ${dir} from manifest does not exist."
            exit 1
        fi
    done

    # Validate all data files from manifest exist on disk
    MISSING_FILES=$("${PYTHON_CMD}" -c "
import json
with open('${MANIFEST_PATH}') as f:
    m = json.load(f)
missing = []
for table, info in m['data_file_distribution'].items():
    for f in info['data_files']:
        import os
        if not os.path.exists(f):
            missing.append(f)
if missing:
    for f in missing:
        print(f'Missing: {f}')
    import sys
    sys.exit(1)
print('OK')
" 2>&1)
    if [[ "${MISSING_FILES}" != "OK" ]]; then
        echo "Error: Some data files from manifest are missing:"
        echo "${MISSING_FILES}"
        exit 1
    fi
    echo "All data files from manifest exist on disk."
    MANIFEST_MODE=1
fi

check_prerequest() {
    local CMD=$1
    local NAME=$2
    if ! ${CMD}; then
        echo "${NAME} is missing. This script depends on cURL to load data to Doris."
        exit 1
    fi
}

check_prerequest "curl --version" "curl"

# load tables
source "${CURDIR}/../conf/doris-cluster.conf"
export MYSQL_PWD=${PASSWORD}

echo "Parallelism: ${PARALLEL}"
echo "FE_HOST: ${FE_HOST}"
echo "FE_HTTP_PORT: ${FE_HTTP_PORT}"
echo "USER: ${USER}"
echo "DB: ${DB}"

# Function to find all data files for a table across all data directories
# Usage: find_table_files <table_name> <pattern>
find_table_files() {
    local table_name=$1
    local pattern=$2
    local files=()
    for dir in "${SEARCH_DIRS[@]}"; do
        while IFS= read -r -d '' f; do
            files+=("$f")
        done < <(find "${dir}" -maxdepth 1 -name "${pattern}" -print0 2>/dev/null)
    done
    if [[ ${#files[@]} -eq 0 ]]; then
        echo "Error: No data files found for table ${table_name} with pattern '${pattern}' in directories: ${SEARCH_DIRS[*]}" >&2
        exit 1
    fi
    printf '%s\n' "${files[@]}"
}

# Function to get data files for a table from manifest
# Usage: get_manifest_files <table_name>
get_manifest_files() {
    local table_name=$1
    "${PYTHON_CMD}" -c "
import json
with open('${MANIFEST_PATH}') as f:
    m = json.load(f)
if '${table_name}' not in m['data_file_distribution']:
    import sys
    sys.exit(1)
for f in m['data_file_distribution']['${table_name}']['data_files']:
    print(f)
" 2>/dev/null
}

function load_region() {
    echo "$*"
    if [[ -z ${TXN_ID} ]]; then
        curl -s --location-trusted -u "${USER}":"${PASSWORD}" -H "Expect: 100-continue" -H "column_separator:|" \
            -H "columns: r_regionkey, r_name, r_comment, temp" \
            -T "$*" http://"${FE_HOST}":"${FE_HTTP_PORT}"/api/"${DB}"/region/_stream_load
    else
        curl -s --location-trusted -u "${USER}":"${PASSWORD}" -H "Expect: 100-continue" -H "column_separator:|" \
            -H "label:${TXN_ID}_region" \
            -H "columns: r_regionkey, r_name, r_comment, temp" \
            -T "$*" http://"${FE_HOST}":"${FE_HTTP_PORT}"/api/"${DB}"/region/_stream_load
    fi
}
