# start load
start_time=$(date +%s)
echo "Start time: $(date)"

# Load small tables
if [[ ${MANIFEST_MODE} -eq 1 ]]; then
    # Use manifest to get exact file paths
    region_file=$(get_manifest_files "region" | head -1)
    nation_file=$(get_manifest_files "nation" | head -1)
    supplier_file=$(get_manifest_files "supplier" | head -1)
    customer_file=$(get_manifest_files "customer" | head -1)
    part_file=$(get_manifest_files "part" | head -1)
else
    region_file=$(find_table_files region "region.tbl" | head -1)
    nation_file=$(find_table_files nation "nation.tbl" | head -1)
    supplier_file=$(find_table_files supplier "supplier.tbl" | head -1)
    customer_file=$(find_table_files customer "customer.tbl" | head -1)
    part_file=$(find_table_files part "part.tbl" | head -1)
fi

load_region "${region_file}"
load_nation "${nation_file}"
load_supplier "${supplier_file}"
load_customer "${customer_file}"
load_part "${part_file}"

# set parallelism

# 以PID为名, 防止创建命名管道时与已有文件重名，从而失败
fifo="/tmp/$$.fifo"
# 创建命名管道
mkfifo "${fifo}"
# 以读写方式打开命名管道，文件标识符fd为3，fd可取除0，1，2，5外0-9中的任意数字
exec 3<>"${fifo}"
# 删除文件, 也可不删除, 不影响后面操作
rm -rf "${fifo}"

# 在fd3中放置$PARALLEL个空行作为令牌
for ((i = 1; i <= PARALLEL; i++)); do
    echo >&3
done

date
# Collect lineitem files
if [[ ${MANIFEST_MODE} -eq 1 ]]; then
    mapfile -t lineitem_files < <(get_manifest_files "lineitem")
else
    mapfile -t lineitem_files < <(find_table_files lineitem "lineitem.tbl*")
fi
for file in "${lineitem_files[@]}"; do
    # 领取令牌, 即从fd3中读取行, 每次一行
    # 对管道，读一行便少一行，每次只能读取一行
    # 所有行读取完毕, 执行挂起, 直到管道再次有可读行
    # 因此实现了进程数量控制
    read -r -u3

    # 要批量执行的命令放在大括号内, 后台运行
    {
        load_lineitem "${file}"
        echo "----loaded ${file}"
        sleep 2
        # 归还令牌, 即进程结束后，再写入一行，使挂起的循环继续执行
        echo >&3
    } &
done

date
if [[ ${MANIFEST_MODE} -eq 1 ]]; then
    mapfile -t orders_files < <(get_manifest_files "orders")
else
    mapfile -t orders_files < <(find_table_files orders "orders.tbl*")
fi
for file in "${orders_files[@]}"; do
    read -r -u3
    {
        load_orders "${file}"
        echo "----loaded ${file}"
        sleep 2
        echo >&3
    } &
done

date
if [[ ${MANIFEST_MODE} -eq 1 ]]; then
    mapfile -t partsupp_files < <(get_manifest_files "partsupp")
else
    mapfile -t partsupp_files < <(find_table_files partsupp "partsupp.tbl*")
fi
for file in "${partsupp_files[@]}"; do
    read -r -u3
    {
        load_partsupp "${file}"
        echo "----loaded ${file}"
        sleep 2
        echo >&3
    } &
done

# 等待所有的后台子进程结束
wait
# 删除文件标识符
exec 3>&-

end_time=$(date +%s)
echo "End time: $(date)"

echo "Finish load tpch data, Time taken: $((end_time - start_time)) seconds"
echo '============================================'
